public class MathsFunction {
    public static void main(String[] args) {
        
        System.out.println("Absolute:" + Math.abs(-20));
        System.out.println("Round:" + Math.round(2.44789));

        int a = 20;
        int b = 10;
         System.out.println("Maximum:" + Math.max(a,b));
         System.out.println("Minimum:" + Math.min(a,b));
         System.out.println("Power:" + Math.pow(5,2));
    }
    
}
