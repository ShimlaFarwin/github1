public class TypeCasting {
    public static void main(String[] args) {
        
      /*
      Type Casting in java
       ----------------------
        1. Widening casting

         byte -> short -> char -> int -> long -> float -> double

         2. Narrowing casting

         byte <- short <- char <- int <- long <- float <- double
       
       */  

         int a =10;
         long b = a;
         System.out.println("A is " +a);
         System.out.println("B is " +b);

         


    }
    
}
